print("arithmetic")
print(5 + 6)
print(5 - 6)
print(5 * 6)
print(5 / 2)
print(5 // 2)
print(5 % 2)
print(5 ** 2)

print("relational")
print(5 == 6)
print(5 != 6)
print(5 > 6)
print(5 < 6)
print(5 >= 5)
print(5 <= 4)

print("logical")
print(True and False)
print(True or False)
print(not True)
print(5 > 3 and 2 < 4)

print("bitwise")
print(5 & 3)
print(5 | 3)
print(5 ^ 3)
print(~5)
print(5 << 1)
print(5 >> 1)

print("membership")
names = ["ali", "sara", "amina"]
print("ali" in names)
print("hamza" in names)
print("hamza" not in names)

